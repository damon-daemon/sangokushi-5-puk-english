"""Assemble notes/worker_pack.md: the compact context a message translation worker reads
(besides notes/msg_worker.md and its own chunk file). Re-run after changing tl/msg/00.txt
or the DS 3 English. Sources:
  tl/msg/00.txt                      block-0 inserts {C0}..{C65} (our English)
  DS 3 script/arm9_strings.json + tl/arm9.txt   UI terms (jp by address, en by address)
  notes/chunks/*.txt                 only terms that occur in the todo text are listed

usage: tools/dev/workerpack.py
"""
import collections, glob, json, os, re, sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
import setup, tl

DS3 = os.path.expanduser('~/Projects/sangokushi_ds_3_translation/')
FW = {chr(c): chr(c - 0xFEE0) for c in range(0xFF01, 0xFF5F)}


def hira(s):
    """Half-width katakana -> full-width hiragana-ish key for matching (via NFKC + kata->hira)."""
    import unicodedata
    s = unicodedata.normalize('NFKC', s)
    return ''.join(chr(ord(c) - 0x60) if 'ァ' <= c <= 'ヶ' else c for c in s)


def ui_terms(todo):
    jp = {x['addr']: x['jp'] for x in json.load(open(DS3 + 'script/arm9_strings.json', encoding='utf-8'))}
    en = {}
    for ln in open(DS3 + 'tl/arm9.txt', encoding='utf-8'):
        m = re.match(r'@([0-9A-F]{8})\t(.*)', ln.rstrip('\n'))
        if m:
            en[m.group(1)] = m.group(2).strip()
    people = {x['jp'] for x in json.load(open(DS3 + 'script/names_officers.json', encoding='utf-8'))}
    out = {}
    for a, j in jp.items():
        e = en.get(a, '')
        j = re.sub(r'\{[0-9A-F]{2}\}|[　 ]', '', j)
        if not (2 <= len(j) <= 8) or not e or len(e) < 4 or re.search(r'[%\d.]', j + e) or j in people \
                or e in ('Yes', 'None'):
            continue
        if hira(j) in todo:
            out.setdefault(j, e)
    return out


def inserts():
    blocks = tl.load_blocks()
    j0 = tl.jp_block(blocks, 0)
    recs = tl.parse_tl(tl.tl_path(0))
    words = collections.OrderedDict()
    for (mid, n) in sorted(j0):
        words.setdefault(mid, []).append(recs.get((mid, n), ''))
    return words


def main():
    todo = hira(''.join(open(f, encoding='utf-8').read() for f in glob.glob(
        os.path.join(setup.ROOT, 'notes', 'chunks', 'c*.txt'))))
    w = inserts()
    p = ['# Worker pack (generated by tools/dev/workerpack.py - do not edit)\n',
         '## 1. Block-0 inserts {C0}..{C65} (the game picks one variant per speaker)\n']
    keep, drop = [], []
    for c, vs in w.items():
        u = list(dict.fromkeys(v for v in vs if v))
        (keep if u else drop).append((c, u))
    p.append('Print a word (keep or drop freely; write the word yourself if it reads better):')
    p += ['- {C%d} = %s' % (c, ' / '.join(u)) for c, u in keep]
    p.append('\nEmpty in English (verb endings and particles: drop them or leave them, they print nothing;'
             ' never let the sentence depend on them): ' + ' '.join('{C%d}' % c for c, _ in drop) + '\n')
    terms = ui_terms(todo)
    p.append('## 2. UI terms from DS 3 (menus/commands; use these words when the text names a command or stat;'
             ' they are DS 3 menu labels, so in a sentence write the full word: Valor, not Val)\n')
    p.append(' · '.join('%s %s' % kv for kv in sorted(terms.items(), key=lambda kv: (len(kv[0]), kv[0]))) + '\n')
    out = '\n'.join(p)
    with open(os.path.join(setup.ROOT, 'notes', 'worker_pack.md'), 'w', encoding='utf-8') as f:
        f.write(out)
    print('notes/worker_pack.md: %d bytes, %d UI terms' % (len(out.encode()), len(terms)))


if __name__ == '__main__':
    main()
