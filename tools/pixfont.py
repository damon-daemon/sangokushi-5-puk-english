SPACE_ADV = 3


def _parse():
    out, lines, i = {}, _ART.strip('\n').split('\n'), 0
    while i < len(lines):
        c, w = lines[i][0], int(lines[i][2:])
        rows = lines[i + 1:i + 13]
        for r in rows:
            assert len(r) == w and set(r) <= set('.#'), (c, r)
        out[c] = (w, rows)
        i += 13
    return out


def glyphs():
    """{char: (bytes of 16 rows, advance)} for ' '..'~'."""
    art = _parse()
    out = {' ': (bytes(CELL_H), SPACE_ADV)}
    for c in map(chr, range(0x21, 0x7F)):
        w, rows = art[c]
        cell = bytearray(CELL_H)
        for y, r in enumerate(rows):
            cell[TOP + y] = sum(0x80 >> x for x, p in enumerate(r) if p == '#')
        if c.isdigit() and w < DIGIT_W:   # tabular figures: every digit DIGIT_W wide
            pad = (DIGIT_W - w + 1) // 2
            cell = bytearray(r >> pad for r in cell)
            w = DIGIT_W
        out[c] = (bytes(cell), w + SPACING)
    return out


def preview(path, text='The quick brown fox jumps over the lazy dog! 0123456789 (Cao Cao) "Liu Bei", Zhuge Liang & Xiahou Dun; 50% #$*+-./:<=>?@[\\]^_`{|}~'):
    from PIL import Image
    g = glyphs()
    lines = [''.join(map(chr, range(0x20, 0x7F)))] + [text[i:i + 60] for i in range(0, len(text), 60)]
    W = max(sum(g[c][1] for c in t) for t in lines) + 4
    im = Image.new('RGB', (W, CELL_H * len(lines)), (30, 40, 70))
    for k, t in enumerate(lines):
        x = 2
        for c in t:
            rows, adv = g[c]
            for y in range(CELL_H):
                for i in range(CELL_W):
                    if rows[y] & (0x80 >> i):
                        im.putpixel((x + i, k * CELL_H + y), (255, 255, 255))
            x += adv
    im.resize((W * 3, im.height * 3), Image.NEAREST).save(path)


if __name__ == '__main__':
    import sys
    preview(sys.argv[1] if len(sys.argv) > 1 else 'build/dev/pixfont.png')
