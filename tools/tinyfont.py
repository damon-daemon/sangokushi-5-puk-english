def _parse(art):
    out = {}
    for line in art.strip('\n').splitlines():
        c, rows = line[0], line[2:].split()
        out[c] = rows
    return out

SMALL, MID = _parse(SMALL_ART), _parse(MID_ART)
for _f, _w in ((SMALL, 2), (MID, 3)):
    _f[' '] = ['.' * _w]

def render(text, font, spacing=1):
    """-> (width, height, {(x, y)}) of text in font; y 0 = cap top."""
    ink, x, h = set(), 0, 0
    for c in text:
        rows = font[c]
        w = max(len(r) for r in rows)
        for y, r in enumerate(rows):
            for dx, ch in enumerate(r):
                if ch == '#':
                    ink.add((x + dx, y))
        h = max(h, len(rows))
        x += w + spacing
    return max(0, x - spacing), h, ink

