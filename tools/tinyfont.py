    for font, ls in ((SMALL, lines), (MID, mids)):
        for l in ls:
            w, h, ink = render(l, font)
            for (x, yy) in ink:
                im.putpixel((1 + x, y + yy), 255)
            y += (h if font is SMALL else 9) + 2
    im.resize((800, 480), Image.NEAREST).save(sys.argv[1])
